#!/usr/bin/env python3
# Makes package/ce-screensaver/src/atari-logo.h from a 600x600 picture of the
# Atari logo saved as BMP (macOS: sips -s format bmp logo.png --out logo.bmp),
# the one at https://i.ebayimg.com/images/g/jIwAAOSwsblfjFaH/s-l1600.png.
# Coordinates below are for that picture.
#   tools/genlogo.py logo.bmp > package/ce-screensaver/src/atari-logo.h
import struct,sys
d=open(sys.argv[1],'rb').read()
off=struct.unpack_from('<I',d,10)[0]; w,h=struct.unpack_from('<ii',d,18); B=struct.unpack_from('<H',d,28)[0]//8
stride=(w*B+3)&~3
def px(x,y):
    o=off+((h-1-y) if h>0 else y)*stride+x*B; return d[o+2],d[o+1],d[o]
TOP,SYM_BOT,TXT_TOP,BOT=65,394,411,394
X0,X1=105,495
AXIS2=597           # 2 * symbol axis x (298.5)
TXT_SHIFT=5         # centre the text on the symbol axis (photo is slightly off)
rows=[]
for y in range(TOP,BOT+1):
    lit=[max(px(x,y))>110 for x in range(X0,X1+1)]
    runs=[];x=0;n=len(lit)
    while x<n:
        if lit[x]:
            s=x
            while x<n and lit[x]: x+=1
            runs.append([s+X0,x-1+X0])
        x+=1
    # merge 1-pixel gaps, drop specks
    m=[]
    for r in runs:
        if m and r[0]-m[-1][1]<=2: m[-1][1]=r[1]
        else: m.append(r)
    m=[r for r in m if r[1]-r[0]>=1]
    sh=TXT_SHIFT if y>=TXT_TOP else 0
    # coordinates in half-pixels relative to the axis
    rows.append([(2*(a+sh)-AXIS2, 2*(b+1+sh)-AXIS2) for a,b in m])
# gradient: median of the middle bar (x 284..313) per symbol row
cols=[]
for y in range(TOP,SYM_BOT+1):
    ps=sorted(px(x,y) for x in range(284,314))
    r=sorted(p[0] for p in ps)[15]; g=sorted(p[1] for p in ps)[15]; b=sorted(p[2] for p in ps)[15]
    cols.append((r,g,b))
# light smoothing (photo/compression noise), monotone ends kept
sm=[]
for i in range(len(cols)):
    win=cols[max(0,i-3):i+4]
    sm.append(tuple(round(sum(c[k] for c in win)/len(win)) for k in range(3)))
cols=sm
out=[]
out.append('/* Generated by tools/genlogo.py from a picture of the Atari logo (600 x 600;')
out.append(' * symbol 330 px tall). Rows top to bottom; each row: runs of lit pixels')
out.append(' * as [x0, x1) in half pixels from the symbol\'s vertical axis. */')
out.append('#define LOGO_SRC_H %d   /* rows in total */' % len(rows))

idx=[0];flat=[]
for r in rows:
    for a,b in r: flat+= [a,b]
    idx.append(len(flat)//2)
maxx=max(max(abs(a),abs(b)) for r in rows for a,b in r)
out.append('#define LOGO_SRC_HALF_W %d  /* half pixels */' % maxx)
def arr(name,typ,vals,per=12):
    out.append('static const %s %s[%d] = {' % (typ,name,len(vals)))
    for i in range(0,len(vals),per): out.append('    '+', '.join(str(v) for v in vals[i:i+per])+',')
    out.append('};')
arr('logo_row_start','uint16_t',idx)
arr('logo_runs','int16_t',flat)
arr('logo_rgb','uint8_t',[c for t in cols for c in t])
print('\n'.join(out))
